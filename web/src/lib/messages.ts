export const messages: Record<Lang, Messages> = { en, fil };

// Dates are plain YYYY-MM-DD strings in Manila time
export function fmtDate(iso: string, lang: Lang, withYear = false): string {
  return new Date(`${iso}T00:00:00Z`).toLocaleDateString(messages[lang].locale, {
    timeZone: "UTC",
    weekday: "short",
    month: "short",
    day: "numeric",
    ...(withYear ? { year: "numeric" } : {}),
  });
}

export function fmtTime(ts: string, lang: Lang): string {
  return new Date(ts).toLocaleTimeString(messages[lang].locale, { timeZone: "Asia/Manila", hour: "numeric", minute: "2-digit" });
}

export function fmtMonth(iso: string, lang: Lang): string {
  return new Date(`${iso}T00:00:00Z`).toLocaleDateString(messages[lang].locale, { timeZone: "UTC", month: "long", year: "numeric" });
}
